"""Write po/dsperate.pot, the template every po/<code>.po translates, from the
frontend's sources.

    tools/i18n_extract.py            rewrite po/dsperate.pot
    tools/i18n_extract.py --check    exit 1 if it is out of date (CI)

Collects the string literals given to tr(), trf(), N_() (the English text)
and trc(), NC_() (a context, then the text) in src/frontend. Adjacent
literals join as in C. A comment line starting "TRANSLATORS:" just above a
call becomes a note for translators ("#." in the template). The output has no
dates, so it changes only when the strings do.

To bring a translation up to date with a new template, gettext's
    msgmerge --update --no-fuzzy-matching po/<code>.po po/dsperate.pot
or a translation tool (Weblate, Poedit) does it. See docs/translating.md.
"""
import os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SCAN = ['src/frontend']
SKIP = ['src/frontend/i18n']        # the mechanism itself, whose comments show examples
POT = 'po/dsperate.pot'

LIT = r'"(?:[^"\\\n]|\\.)*"'
LITS = r'(%s(?:\s*%s)*)' % (LIT, LIT)
CALL = re.compile(r'\b(tr|trf|N_)\(\s*' + LITS + r'|\b(trc|NC_)\(\s*(' + LIT + r')\s*,\s*' + LITS)


def c_unescape(lits):
    """The bytes a run of adjacent C string literals spells."""
    out = bytearray()
    for lit in re.findall(LIT, lits):
        body = lit[1:-1].encode('utf-8')
        i = 0
        while i < len(body):
            c = body[i]; i += 1
            if c != 0x5C:
                out.append(c); continue
            e = chr(body[i]); i += 1
            if e in 'ntrabfv':
                out.append(ord({'n': '\n', 't': '\t', 'r': '\r', 'a': '\a', 'b': '\b', 'f': '\f', 'v': '\v'}[e]))
            elif e == 'x':                       # C reads every hex digit that follows
                j = i
                while j < len(body) and chr(body[j]) in '0123456789abcdefABCDEF':
                    j += 1
                out.append(int(body[i:j], 16) & 0xFF); i = j
            elif e in '01234567':
                j = i
                while j < len(body) and j < i + 2 and chr(body[j]) in '01234567':
                    j += 1
                out.append(int(chr(body[i - 1]) + body[i:j].decode(), 8) & 0xFF); i = j
            else:
                out.append(ord(e))
    return bytes(out)


def po_quote(b):
    """A PO string literal for these bytes: UTF-8 as is, control bytes as octal."""
    s = ''
    for ch in b.decode('utf-8'):
        o = ord(ch)
        if ch == '\\': s += '\\\\'
        elif ch == '"': s += '\\"'
        elif ch == '\n': s += '\\n'
        elif ch == '\t': s += '\\t'
        elif o < 0x20 or o == 0x7F: s += '\\%03o' % o
        else: s += ch
    return '"' + s + '"'


def sources():
    for top in SCAN:
        for d, _, files in sorted(os.walk(os.path.join(ROOT, top))):
            rel = os.path.relpath(d, ROOT)
            if any(rel == s or rel.startswith(s + '/') for s in SKIP):
                continue
            for f in sorted(files):
                if f.endswith(('.cpp', '.h')):
                    yield os.path.join(rel, f)


def extract():
    entries = {}          # (ctx, id) -> {'refs': [...], 'notes': [...]}
    order = []
    for rel in sources():
        text = open(os.path.join(ROOT, rel), encoding='utf-8').read()
        lines = text.split('\n')
        for m in CALL.finditer(text):
            if m.group(1):
                ctx, msgid = None, c_unescape(m.group(2))
            else:
                ctx, msgid = c_unescape(m.group(4)), c_unescape(m.group(5))
            if not msgid or (ctx, msgid) == (b'language name', b'ENGLISH'):
                continue   # empty, or the language's name, which render() always writes first
            line = text.count('\n', 0, m.start()) + 1
            if b'\x04' in msgid or (ctx and b'\x04' in ctx):
                sys.exit('%s:%d: a translatable string holds \\x04, which gettext reserves as its context '
                         'separator: pass the button icon as a {n} argument instead' % (rel, line))
            key = (ctx, msgid)
            if key not in entries:
                entries[key] = {'refs': [], 'notes': []}
                order.append(key)
            entries[key]['refs'].append('%s:%d' % (rel, line))
            prev = lines[line - 2].strip() if line >= 2 else ''
            note = re.match(r'//\s*TRANSLATORS:\s*(.*)', prev)
            if note and note.group(1) not in entries[key]['notes']:
                entries[key]['notes'].append(note.group(1))
    return entries, order


def render(entries, order):
    out = [
        '# DSperate\'s frontend strings: the template every po/<code>.po translates.',
        '# Generated by tools/i18n_extract.py from the sources; do not edit by hand.',
        '# docs/translating.md is the guide.',
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: DSperate\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '',
        '#. The language\'s own name, as its speakers write it: what the language',
        '#. setting lists it as (frontend/i18n/i18n.h).',
        'msgctxt "language name"',
        'msgid "ENGLISH"',
        'msgstr ""',
        '',
    ]
    for key in order:
        ctx, msgid = key
        e = entries[key]
        for n in e['notes']:
            out.append('#. ' + n)
        if re.search(rb'\{[1-9]\}', msgid):
            out.append('#. {1}, {2}... are filled in by the program; keep each one, in any order.')
        # Wrap references like xgettext, a few per line.
        refs = e['refs']
        for i in range(0, len(refs), 3):
            out.append('#: ' + ' '.join(refs[i:i + 3]))
        if ctx is not None:
            out.append('msgctxt ' + po_quote(ctx))
        out.append('msgid ' + po_quote(msgid))
        out.append('msgstr ""')
        out.append('')
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv[1:]
    entries, order = extract()
    text = render(entries, order)
    path = os.path.join(ROOT, POT)
    if check:
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if old != text:
            sys.exit('%s is out of date with the sources: run tools/i18n_extract.py and commit it' % POT)
        print('%s: up to date, %d strings' % (POT, len(order)))
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %s: %d strings' % (POT, len(order)))


if __name__ == '__main__':
    main()
